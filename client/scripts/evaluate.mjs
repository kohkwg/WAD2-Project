// Writes docs/EVALUATION.md from the same evaluation the "How it works" page runs.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { runItineraryEvaluation, runSlotEvaluation } from '../src/lib/algo/evaluate.js'
import { fmtRange } from '../src/lib/time.js'

const pct = (x) => (x == null ? '-' : `${Math.round(x * 100)}%`)
const row = (label, name, m) =>
  m.feasible
    ? `| ${label} | ${name} | ${m.stops} | ${m.violations}${m.violationTypes?.length ? ` (${m.violationTypes.join(', ')})` : ''} | ${m.travelMins} | ${pct(m.avgSat)} | ${pct(m.minSat)} | ${m.score.toFixed(3)} | ${m.ms} |`
    : `| ${label} | ${name} | 0 | - | - | - | - | - | ${m.ms} |`

const itin = runItineraryEvaluation()
const slots = runSlotEvaluation()
const lines = [
  '# Evaluation',
  '',
  `Generated by \`pnpm --dir client evaluate\` on ${new Date().toISOString().slice(0, 10)}. Same code and sample listings as the app.`,
  '',
  '## Itinerary generation: beam search vs greedy baseline',
  '',
  'Greedy repeatedly takes the feasible next stop with the highest average group interest, ignoring travel cost and meal coverage. Both use the same candidate pool and hard checks. "Rule breaks" are issues found by re-validating the final plan.',
  '',
  '| Case | Method | Stops | Rule breaks | Travel (min) | Avg interest | Least happy | Score | Runtime (ms) |',
  '|---|---|---|---|---|---|---|---|---|',
]
for (const r of itin) {
  lines.push(row(r.label, 'Beam', r.beam))
  lines.push(row('', 'Greedy', r.greedy))
}
const wins = itin.filter((r) => r.beam.feasible && r.greedy.feasible && r.beam.score > r.greedy.score).length
const both = itin.filter((r) => r.beam.feasible && r.greedy.feasible).length
const minWins = itin.filter((r) => r.beam.feasible && r.greedy.feasible && r.greedy.minSat > r.beam.minSat).length
lines.push('', `Beam scores higher in ${wins} of ${both} feasible cases. Greedy keeps the least happy member happier in ${minWins} of them, and breaks a hard rule in ${itin.filter((r) => r.greedy.violations > 0).length}. Infeasible cases report the conflicting constraint instead of a plan.`, '')
lines.push('## Slot ranking vs earliest common slot', '', '| Case | Method | Slot | Can come | Sociable hours |', '|---|---|---|---|---|')
for (const r of slots) {
  const f = (m) => (m.found ? `${fmtRange(m.start, m.end)} | ${m.attendees} of ${m.of} | ${pct(m.prefFraction)}` : 'None | - | -')
  lines.push(`| ${r.label} | Ranked | ${f(r.ranked)} |`)
  lines.push(`| | Earliest | ${f(r.baseline)} |`)
}
lines.push('', '## Limitations', '', '- Travel times are estimates (distance with a detour factor) unless the OneMap server is configured.', '- Sample listings have approximate hours; scores depend on the chosen weights, which are a design choice.', '- Eight hand-made cases are not a benchmark; they show behaviour on situations the plan calls out.', '')
const out = fileURLToPath(new URL('../../docs/EVALUATION.md', import.meta.url))
writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${out}`)
