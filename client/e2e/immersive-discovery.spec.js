import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/*.supabase.co/**', route => route.abort())
})

test('OneMap hero preview opens the live map with real event pins and a usable list', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: "Singapore’s got plans for you." })).toBeVisible()
  await expect(page.locator('.hero-map-status')).toContainText(/\d+ upcoming events? on the map/)
  await expect(page.locator('.hero-map-credit')).toContainText('Singapore Land Authority')
  await expect(page.locator('.hero-map [data-marker]')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('hero-desktop.png') })
  await page.getByRole('button', { name: 'Explore the map' }).click()
  const map = page.getByRole('region', { name: 'Explore events on the Singapore map' })
  await expect(map.locator('img.leaflet-tile').first()).toHaveAttribute('src', /onemap\.gov\.sg\/maps\/tiles\/Default\//)
  await expect(map.locator('[data-marker]').first()).toBeVisible()
  await expect(map.locator('.map-surface')).toHaveCSS('opacity', '1')
  await map.screenshot({ path: testInfo.outputPath('interactive-map-desktop.png') })
  await map.locator('[data-marker]').first().click()
  await expect(map.getByRole('region', { name: 'Selected map events' })).toBeVisible()
  // Rail items open the same preview and move focus into it.
  await map.locator('.rail-item').first().click()
  await expect(map.locator('.map-preview h2')).toBeFocused()
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await expect(map).toHaveCount(0)
  await page.getByLabel('Search by title, description or venue').fill('no-such-event-XYZ')
  await expect(page.getByRole('heading', { name: 'No events found' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear search and filters' }).click()
  await expect(page.locator('.event-card').first()).toBeVisible()
  expect(errors).toEqual([])
})

test('dark theme swaps to OneMap night tiles and Search this area narrows the rail', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/discover?view=map')
  const map = page.getByRole('region', { name: 'Explore events on the Singapore map' })
  await expect(map.locator('img.leaflet-tile').first()).toHaveAttribute('src', /\/tiles\/Night\//)
  await expect(map.locator('[data-marker]').first()).toBeVisible()
  await expect(map.getByRole('button', { name: 'Search this area' })).toHaveCount(0)
  // Any visitor-driven view change (pan, keyboard or zoom) offers the area search.
  await map.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await map.getByRole('button', { name: 'Search this area' }).click()
  await expect(map.getByRole('heading', { name: 'In this area' })).toBeVisible()
  await map.getByRole('button', { name: /Clear area/ }).click()
  await expect(map.getByRole('heading', { name: 'On the map' })).toBeVisible()
})

test('mobile hero reflows, reduced motion stays static, and live map remains keyboard accessible', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.hero-map')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('hero-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.locator('html')).not.toHaveClass(/lenis/)
  await page.goto('/discover')
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  const marker = page.locator('[data-marker]').first()
  await expect(marker).toBeVisible()
  const bounds = await marker.boundingBox()
  expect(bounds.width).toBeGreaterThanOrEqual(44)
  await page.getByRole('region', { name: 'Explore events on the Singapore map' }).screenshot({ path: testInfo.outputPath('interactive-map-mobile.png') })
  await marker.focus()
  await marker.press('Enter')
  await expect(page.getByRole('region', { name: 'Selected map events' })).toBeVisible()
  await page.getByRole('button', { name: 'Close event preview' }).click()
  await expect(marker).toBeFocused()
})
