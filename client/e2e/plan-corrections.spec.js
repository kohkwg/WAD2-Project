import { test, expect } from '@playwright/test'

test('a host can correct details and cancel an unfinished jio without leaving planning actions active', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('openjio:onboarding:v1', 'done'))
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: /, Mei\?/ })).toBeVisible()
  await page.goto('/h/h-catchup')
  await page.getByRole('button', { name: 'Edit details', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit hangout details', exact: true })
  await edit.getByLabel('Name', { exact: true }).fill('Updated catch-up')
  await edit.getByRole('button', { name: 'Save details', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Updated catch-up' })).toBeVisible()
  const best = page.getByRole('tab', { name: /^Best times/ })
  if (await best.isVisible()) await best.click()
  await page.getByRole('button', { name: 'Lock this time', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel hangout', exact: true }).click()
  await page.getByRole('dialog', { name: 'Cancel this hangout?', exact: true }).getByRole('button', { name: 'Cancel hangout', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit details', exact: true })).toHaveCount(0)
})

test('hiding group overlap clears a selected grid highlight too', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('openjio:onboarding:v1', 'done'))
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: /, Mei\?/ })).toBeVisible()
  await page.goto('/h/h-catchup')
  await expect(page.getByRole('heading', { level: 1, name: 'Saturday catch-up', exact: true })).toBeVisible()
  const best = page.getByRole('tab', { name: /^Best times/ })
  if (await best.isVisible()) await best.click()
  await page.getByRole('button', { name: 'Show on grid', exact: true }).first().click()
  const overlap = page.getByRole('dialog', { name: 'Group overlap', exact: true })
  await expect(overlap).toBeVisible()
  await overlap.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(overlap).toBeHidden()
  await expect(page.getByRole('button', { name: 'Show on grid', exact: true }).first()).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'View group overlap', exact: true })).toHaveAttribute('aria-expanded', 'false')
})

test('unsaved profile edits are retained when leaving is declined', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('openjio:onboarding:v1', 'done'))
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: /, Mei\?/ })).toBeVisible()
  await page.goto('/profile')
  await page.getByLabel('Display name', { exact: true }).fill('Unsaved display name')
  await page.getByRole('link', { name: 'Discover', exact: true }).first().click()
  const leave = page.getByRole('dialog', { name: 'Leave without saving?', exact: true })
  await expect(leave).toBeVisible()
  await leave.getByRole('button', { name: 'Stay', exact: true }).click()
  await expect(leave).toBeHidden()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByLabel('Display name', { exact: true })).toHaveValue('Unsaved display name')
})
